"""Build AdrenoBLAS's kernel catalogue from the on-device tuning results.

For every tuned shape and layout (results/<M>x<N>x<K>_<la><lb>.json, written by sweep.py), take the fastest
kernel that passed the reference check; add one small fallback kernel per layout (64 x 32 tile); compile
each with M, N, K as specialization constants; write ablas_kernels.h (SPIR-V words + selection table).
"""
import json, pathlib, subprocess
from gen import glsl, parse, tile

HERE = pathlib.Path(__file__).resolve().parent
LAYOUTS = ("NN", "TN", "TT", "RC")  # NT is packed (direct NT kernels: 2.4 TFLOP/s on the 850); RC = K-minor tiles

def spv_words(src, out):
    out.parent.mkdir(parents=True, exist_ok=True)
    src_path = out.with_suffix(".comp")
    src_path.write_text(src)
    subprocess.run(["glslc", "--target-env=vulkan1.3", "-O", str(src_path), "-o", str(out)], check=True)
    b = out.read_bytes()
    return [int.from_bytes(b[i:i + 4], "little") for i in range(0, len(b), 4)]

def main():
    tuned, kernels = [], {}
    for f in sorted((HERE / "results").glob("*_??.json")):
        shape, lay = f.stem.rsplit("_", 1)
        if lay not in LAYOUTS:
            continue
        M, N, K = map(int, shape.split("x"))
        best = next((j for j in json.load(open(f)) if j.get("ok") and parse(j["name"]).get("sw", 0) == 0), None)
        if best:
            kernels.setdefault(best["name"], parse(best["name"]))
            tuned.append((lay, M, N, K, best["name"], best["tflops"]))
    for lay in LAYOUTS:
        fb = dict(la=lay[0], lb=lay[1], wm=1, wn=1, tm=1, tn=1, nt=32, acc="f16", ku=1, pf=0, sw=0, sa=0, sb=0, kc=0, dual=0)
        from gen import name
        kernels.setdefault(name(fb), fb)
    names = sorted(kernels)
    H = ["// Generated by build_lib.py from results/*.json: do not edit.", "#pragma once", "#include <stdint.h>", "",
         "typedef struct { const char* name; char la, lb; uint32_t bm, bn, threads; const uint32_t* spv; uint32_t words; } ablas_kernel_t;",
         "typedef struct { char la, lb; uint32_t m, n, k; uint16_t kernel; float tflops; } ablas_tune_t;", ""]
    for i, n in enumerate(names):
        w = spv_words(glsl(kernels[n], 0, 0, 0, spec=True), HERE / "build/spv" / f"{n}.spv")
        H.append(f"static const uint32_t ablas_spv_{i}[] = {{" + ",".join(f"0x{x:08x}" for x in w) + "};")
    for t in ("transpose", "transpose64", "tile_copy"):
        w = spv_words((HERE / f"{t}.comp").read_text(), HERE / f"build/spv/{t}.spv")
        H.append(f"static const uint32_t ablas_{t}_spv[] = {{" + ",".join(f"0x{x:08x}" for x in w) + "};")
    H.append("static const ablas_kernel_t ablas_kernels[] = {")
    for i, n in enumerate(names):
        c = kernels[n]
        BM, BN = tile(c)
        H.append(f'  {{"{n}", \'{c["la"]}\', \'{c["lb"]}\', {BM}, {BN}, {64 * c["wm"] * c["wn"]}, ablas_spv_{i}, sizeof(ablas_spv_{i}) / 4}},')
    H.append("};")
    H.append("static const ablas_tune_t ablas_tuning[] = {")
    for lay, M, N, K, n, tf in sorted(tuned):
        H.append(f"  {{'{lay[0]}', '{lay[1]}', {M}, {N}, {K}, {names.index(n)}, {tf:.2f}f}},  // {n}")
    H.append("};")
    (HERE / "ablas_kernels.h").write_text("\n".join(H) + "\n")
    print(f"{len(names)} kernels, {len(tuned)} tuned shapes -> ablas_kernels.h")
    for t in sorted(tuned):
        print("  ", t)

def build_840():
    """Adreno 840 ALU backend: results/alu840_<M>x<N>x<K>.json (sweep_alu.py) -> ablas_kernels_840.h.
    Per tuned shape, the fastest correct kernel for each driver (0 = Qualcomm, 1 = Mesa Turnip; for Turnip the
    bank-aware-RA on/off choice is baked into the kernel's SPIR-V, gen_alu.mark_nobankra). A fallback kernel
    (alu_gg_64x64: M, N multiples of 64, K of 4) covers untuned shapes. Separate file and names, so
    ablas_kernels.h (the 850 catalogue) does not change."""
    import gen_alu
    tuned, used = [], {("alu_gg_64x64", False): None}
    for f in sorted((HERE / "results").glob("alu840_*x*x*.json")):
        M, N, K = map(int, f.stem.split("_", 1)[1].split("x"))
        res = json.load(open(f))
        for drv, comps in ((0, ("stock",)), (1, ("turnip-bank", "turnip-nobank"))):
            best = next((j for j in res if j.get("ok") and j.get("compiler") in comps), None)
            if best:
                key = (best["name"], best["compiler"] == "turnip-nobank")
                used.setdefault(key, None)
                tuned.append((drv, M, N, K, key, best["tflops"]))
    keys = sorted(used)
    H = ["// Generated by build_lib.py (build_840) from results/alu840_*.json: do not edit.", "#pragma once",
         "#include <stdint.h>", "",
         "typedef struct { const char* name; uint32_t bm, bn, threads, kstep; const uint32_t* spv; uint32_t words; } ablas840_kernel_t;",
         "typedef struct { uint8_t driver; uint32_t m, n, k; uint16_t kernel; float tflops; } ablas840_tune_t;  // driver: 0 Qualcomm, 1 Turnip",
         ""]
    for i, (n, nobank) in enumerate(keys):
        c = gen_alu.parse(n)
        w = spv_words(gen_alu.glsl(c, 0, 0, 0, spec=True), HERE / "build/spv840" / f"{n}.spv")
        if nobank:
            w = gen_alu.mark_nobankra(w)
        H.append(f"static const uint32_t ablas840_spv_{i}[] = {{" + ",".join(f"0x{x:08x}" for x in w) + "};")
    w = spv_words((HERE / "copy840.comp").read_text(), HERE / "build/spv840/copy840.spv")
    H.append("static const uint32_t ablas840_copy_spv[] = {" + ",".join(f"0x{x:08x}" for x in w) + "};")
    H.append("static const ablas840_kernel_t ablas840_kernels[] = {")
    for i, (n, nobank) in enumerate(keys):
        c = gen_alu.parse(n)
        H.append(f'  {{"{n}{"/nobankra" if nobank else ""}", {c[1]}, {c[2]}, {gen_alu.threads(c)}, {gen_alu.kstep(c)}, '
                 f'ablas840_spv_{i}, sizeof(ablas840_spv_{i}) / 4}},')
    H.append("};")
    H.append("static const ablas840_tune_t ablas840_tuning[] = {")
    for drv, M, N, K, key, tf in sorted(tuned):
        H.append(f"  {{{drv}, {M}, {N}, {K}, {keys.index(key)}, {tf:.2f}f}},  // {key[0]}{'/nobankra' if key[1] else ''}")
    H.append("  {255, 0, 0, 0, 0, 0.0f},  // end")
    H.append("};")
    (HERE / "ablas_kernels_840.h").write_text("\n".join(H) + "\n")
    print(f"840: {len(keys)} kernels, {len(tuned)} tuned (shape, driver) entries -> ablas_kernels_840.h")
    for t in sorted(tuned):
        print("  ", t)


if __name__ == "__main__":
    main()
    build_840()
