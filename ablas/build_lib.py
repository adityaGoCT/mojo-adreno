"""Build AdrenoBLAS's kernel catalogue from the on-device tuning results.

For every tuned shape and layout (results/<M>x<N>x<K>_<la><lb>.json, written by sweep.py), take the fastest
kernel that passed the reference check; add one small fallback kernel per layout (64 x 32 tile); compile
each with M, N, K as specialization constants; write ablas_kernels.h (SPIR-V words + selection table).
"""
import json, pathlib, subprocess
from gen import glsl, parse, tile

HERE = pathlib.Path(__file__).resolve().parent
LAYOUTS = ("NN", "TN", "TT", "RC")  # NT is packed (direct NT kernels: 2.4 TFLOP/s on the 850); RC = K-minor tiles

def spv_words(src, out):
    out.parent.mkdir(parents=True, exist_ok=True)
    src_path = out.with_suffix(".comp")
    src_path.write_text(src)
    subprocess.run(["glslc", "--target-env=vulkan1.3", "-O", str(src_path), "-o", str(out)], check=True)
    b = out.read_bytes()
    return [int.from_bytes(b[i:i + 4], "little") for i in range(0, len(b), 4)]

def main():
    tuned, kernels = [], {}
    for f in sorted((HERE / "results").glob("*_??.json")):
        shape, lay = f.stem.rsplit("_", 1)
        if lay not in LAYOUTS:
            continue
        M, N, K = map(int, shape.split("x"))
        best = next((j for j in json.load(open(f)) if j.get("ok") and parse(j["name"]).get("sw", 0) == 0), None)
        if best:
            kernels.setdefault(best["name"], parse(best["name"]))
            tuned.append((lay, M, N, K, best["name"], best["tflops"]))
    for lay in LAYOUTS:
        fb = dict(la=lay[0], lb=lay[1], wm=1, wn=1, tm=1, tn=1, nt=32, acc="f16", ku=1, pf=0, sw=0, sa=0, sb=0, kc=0, dual=0)
        from gen import name
        kernels.setdefault(name(fb), fb)
    names = sorted(kernels)
    H = ["// Generated by build_lib.py from results/*.json: do not edit.", "#pragma once", "#include <stdint.h>", "",
         "typedef struct { const char* name; char la, lb; uint32_t bm, bn, threads; const uint32_t* spv; uint32_t words; } ablas_kernel_t;",
         "typedef struct { char la, lb; uint32_t m, n, k; uint16_t kernel; float tflops; } ablas_tune_t;", ""]
    for i, n in enumerate(names):
        w = spv_words(glsl(kernels[n], 0, 0, 0, spec=True), HERE / "build/spv" / f"{n}.spv")
        H.append(f"static const uint32_t ablas_spv_{i}[] = {{" + ",".join(f"0x{x:08x}" for x in w) + "};")
    for t in ("transpose", "transpose64", "tile_copy"):
        w = spv_words((HERE / f"{t}.comp").read_text(), HERE / f"build/spv/{t}.spv")
        H.append(f"static const uint32_t ablas_{t}_spv[] = {{" + ",".join(f"0x{x:08x}" for x in w) + "};")
    H.append("static const ablas_kernel_t ablas_kernels[] = {")
    for i, n in enumerate(names):
        c = kernels[n]
        BM, BN = tile(c)
        H.append(f'  {{"{n}", \'{c["la"]}\', \'{c["lb"]}\', {BM}, {BN}, {64 * c["wm"] * c["wn"]}, ablas_spv_{i}, sizeof(ablas_spv_{i}) / 4}},')
    H.append("};")
    H.append("static const ablas_tune_t ablas_tuning[] = {")
    for lay, M, N, K, n, tf in sorted(tuned):
        H.append(f"  {{'{lay[0]}', '{lay[1]}', {M}, {N}, {K}, {names.index(n)}, {tf:.2f}f}},  // {n}")
    H.append("};")
    (HERE / "ablas_kernels.h").write_text("\n".join(H) + "\n")
    print(f"{len(names)} kernels, {len(tuned)} tuned shapes -> ablas_kernels.h")
    for t in sorted(tuned):
        print("  ", t)

if __name__ == "__main__":
    main()
