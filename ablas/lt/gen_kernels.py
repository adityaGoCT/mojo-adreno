"""Builds AdrenoBLASLt's operation kernels into ablaslt_kernels.h (SPIR-V arrays and a table).
  python3 gen_kernels.py
kernels/*.comp are compiled as they are. fa3 (causal flash attention, ../llama3b/gen_attn.py) is generated with its
two Llama-3B constants made parameters: the KV head of query head z is z / group (push constant; 3 in Llama 3.2 3B)
and the output's row of tiles is n_heads * 8 tiles wide (gl_NumWorkGroups.y * 8; 192 there). famask128/256 (masked,
non-causal attention for π0's Gemma prefix, its action expert and SigLIP) are generated by famask() below.
"""
import pathlib, subprocess, sys
HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "llama3b"))
import gen_attn

def fa3():
    src = gen_attn.fa3()
    for old, new in [
        ("layout(push_constant) uniform P { uint M; float scale; } pc;",
         "layout(push_constant) uniform P { uint M; float scale; uint group; } pc;"),
        ("g = z / 3u,", "g = z / pc.group,"),
        ("(row0 / 64u) * 192u", "(row0 / 64u) * (gl_NumWorkGroups.y * 8u)"),
    ]:
        assert src.count(old) == 1, old
        src = src.replace(old, new)
    return src

def famask(HD, mode=""):
    """Masked (non-causal) flash attention with heads of HD (128 or 256), for prefix-LM and encoder attention.
    Workgroup = 64 query rows of one head of one batch, 2 subgroups. Two passes over the key blocks, as fa3: the
    first finds each row's max and sum, the second recomputes S, writes P = exp(S scale - max) / sum into shared
    memory and multiplies it into V. A subgroup holds one 64 x 64 output accumulator: two long-lived ones hang the
    850 (../../driver_bugs #4). So the second pass runs once per 128 output dims (HD / 128 times), subgroup s owning
    dims [128 h + 64 s, 128 h + 64 s + 64) in round h. Key j of a batch is visible to query row r (row within the
    batch) when
        j < kvalid  or  (sbase <= j < sbase + scount  and  (r >= scausal  or  j - sbase <= r)),
    and blocks [0, nkb) are visited. Q tiles: head z at z * qrows rows, batch b at b * nq rows; K tiles and V^T
    tiles: KV head z / group at krows rows, batch b at b * kbatch keys.
    mode "": out = tiles of [rows, outw], head z's first hdv dims at columns z * hdv (hdv multiple of 8: SigLIP's
    heads of 72 padded to 128), staged through shared memory.
    mode "s", key splits (few query rows, many keys: π0's action expert has 64 rows x 8 heads = 8 workgroups):
    workgroup z index = batch * nsplit + split, split s visiting blocks [s bps, (s + 1) bps). out = each split's
    output normalized by its own sum, row-major [nsplit][heads][qrows][HD] stored straight from the accumulator,
    and st (binding 4) its row max and sum, st[(s * heads + z) * qrows + row]; facombine.comp merges them.
    mode "s1": "s" for splits of at most 2 key blocks (one per subgroup): S is computed once, P stays in shared
    memory for every round (half the matrix work of "s" with heads of 256)."""
    KS, CPS = HD // 16, HD // 128
    A = "coopmat<float16_t, gl_ScopeSubgroup, 64, 16, gl_MatrixUseA>"
    Bm = "coopmat<float16_t, gl_ScopeSubgroup, 16, 64, gl_MatrixUseB>"
    C = "coopmat<float16_t, gl_ScopeSubgroup, 64, 64, gl_MatrixUseAccumulator>"
    RM, CM = "gl_CooperativeMatrixLayoutRowMajor", "gl_CooperativeMatrixLayoutColumnMajor"
    def qk(ind="    "):
        return [ind + f"{C} s = {C}(0);",
                ind + f"for (uint kk = 0u; kk < {KS}u; ++kk) {{",
                ind + f"  {A} a; coopMatLoad(a, q, qa + kk * 1024u, 16u, {RM});",
                ind + f"  {Bm} bb; coopMatLoad(bb, k, kbase + (kb * {KS}u + kk) * 1024u, 16u, {CM});",
                ind + "  s = coopMatMulAdd(a, bb, s);",
                ind + "}",
                ind + f"coopMatStore(s, sh, sb, 17u, {RM});",
                ind + "subgroupMemoryBarrierShared(); subgroupBarrier();"]
    def stats(ind="    "):  # this subgroup's block (in sh) into its running (m, lsum)
        return [ind + "if (valid) {",
                ind + "  float bm = -1e30;",
                ind + "  for (uint j = 0u; j < 16u; ++j) { vec4 v = vec4(sh[sr + j]); for (uint i = 0u; i < 4u; ++i) if (vis(kb * 64u + 4u * j + i, qr)) bm = max(bm, v[i]); }",
                ind + "  if (bm > -1e29) {",
                ind + "    float mn = max(m, bm * scale);",
                ind + "    lsum *= exp(m - mn);",
                ind + "    for (uint j = 0u; j < 16u; ++j) { vec4 v = vec4(sh[sr + j]); for (uint i = 0u; i < 4u; ++i) if (vis(kb * 64u + 4u * j + i, qr)) lsum += exp(v[i] * scale - mn); }",
                ind + "    m = mn;",
                ind + "  }",
                ind + "}"]
    def to_p(ind="    "):  # this subgroup's S tile in sh -> P
        return [ind + "for (uint j = 0u; j < 16u; ++j) {",
                ind + "  vec4 v = vec4(sh[sr + j]), p;",
                ind + "  for (uint i = 0u; i < 4u; ++i) p[i] = valid && vis(kb * 64u + 4u * j + i, qr) ? exp(v[i] * scale - m) * inv : 0.0;",
                ind + "  sh[sr + j] = f16vec4(p);",
                ind + "}"]
    def pv(ind, kt0):  # acc += P (both tiles in sh) V^T[this round's dims]
        return [ind + "for (uint t = 0u; t < 2u; ++t) {",
                ind + f"  uint kt = kb0 + min({kt0} + t, nkb - 1u);  // past the last block: that P tile is all zero",
                ind + "  for (uint kc = 0u; kc < 4u; ++kc) {",
                ind + f"    {A} pa; coopMatLoad(pa, sh, t * 64u * 17u + kc * 4u, 17u, {RM});",
                ind + f"    {Bm} vb; coopMatLoad(vb, vt, vbase + dc * (pc.krows / 16u) * 1024u + (kt * 4u + kc) * 1024u, 16u, {CM});",
                ind + "    acc = coopMatMulAdd(pa, vb, acc);",
                ind + "  }",
                ind + "}"]
    split = mode in ("s", "s1")
    L = ["#version 450",
         "#extension GL_KHR_cooperative_matrix : require",
         "#extension GL_KHR_memory_scope_semantics : require",
         "#extension GL_EXT_shader_explicit_arithmetic_types : require",
         "#extension GL_EXT_shader_16bit_storage : require",
         "#extension GL_KHR_shader_subgroup_basic : require",
         "layout(local_size_x = 128) in;",
         "layout(push_constant) uniform P { uint nq, qrows, krows, kbatch, nkb, kvalid, sbase, scount, scausal; float scale; uint group, outw, hdv, nsplit, bps; } pc;",
         "layout(std430, binding = 0) readonly buffer Q { float16_t q[]; };",
         "layout(std430, binding = 1) readonly buffer K { float16_t k[]; };",
         "layout(std430, binding = 2) readonly buffer VT { float16_t vt[]; };",
         "layout(std430, binding = 3) writeonly buffer O { uvec4 o[]; };",
         "layout(std430, binding = 3) writeonly buffer OH { float16_t oh[]; };",
         "layout(std430, binding = 4) writeonly buffer ST { vec2 st[]; };",
         "shared f16vec4 sh[2 * 64 * 17];",
         "shared vec2 stat[2 * 64];",
         "bool vis(uint j, uint r) {",
         "  return j < pc.kvalid || (j >= pc.sbase && j < pc.sbase + pc.scount && (r >= pc.scausal || j - pc.sbase <= r));",
         "}",
         "void main() {",
         "  uint qb = gl_WorkGroupID.x, z = gl_WorkGroupID.y, b = gl_WorkGroupID.z / pc.nsplit, sp = gl_WorkGroupID.z % pc.nsplit, g = z / pc.group;",
         "  uint sg = gl_SubgroupID, l = gl_SubgroupInvocationID, qr = qb * 64u + l;",
         "  uint kb0 = sp * pc.bps, nkb = min(pc.bps, pc.nkb - kb0);  // this split's key blocks",
         f"  uint qa = (z * pc.qrows + b * pc.nq + qb * 64u) * {HD}u;",
         f"  uint kbase = (g * pc.krows + b * pc.kbatch) * {HD}u;",
         f"  uint vbase = g * {HD}u * pc.krows + b * pc.kbatch * 64u;",
         "  uint sb = sg * 64u * 17u, sr = sb + l * 17u;",
         "  uint row0 = b * pc.nq + qb * 64u, row = row0 + l;",
         "  float scale = pc.scale, m = -1e30, lsum = 0.0;",
         "  // cooperative-matrix ops run unconditionally (the 850 compiler crashes on them under per-subgroup",
         "  // branches): a subgroup past the last block redoes it and ignores the result"]
    if mode == "s1":
        L += ["  uint kb = kb0 + min(sg, nkb - 1u);",
              "  bool valid = sg < nkb;"] + qk("  ") + stats("  ")
    else:
        L += ["  for (uint kp = 0u; 2u * kp < nkb; ++kp) {",
              "    uint kb = kb0 + min(2u * kp + sg, nkb - 1u);",
              "    bool valid = 2u * kp + sg < nkb;"] + qk() + stats() + [
              "    subgroupBarrier();",
              "  }"]
    L += ["  stat[sg * 64u + l] = vec2(m, lsum);",
          "  barrier();",
          "  vec2 o2 = stat[(1u - sg) * 64u + l];",
          "  float mm = max(m, o2.x);",
          "  float tot = lsum * exp(m - mm) + o2.y * exp(o2.x - mm);",
          "  float inv = tot > 0.0 ? 1.0 / tot : 0.0;",
          "  m = mm;"]
    if split:
        L += ["  if (sg == 0u) st[(sp * gl_NumWorkGroups.y + z) * pc.qrows + row] = vec2(m, tot);",
              f"  uint pbase = ((sp * gl_NumWorkGroups.y + z) * pc.qrows + row0) * {HD}u;"]
    if mode == "s1":
        L += to_p("  ") + ["  barrier();",
              f"  for (uint hh = 0u; hh < {CPS}u; ++hh) {{",
              "    uint dc = hh * 2u + sg;  // this round's 64 output dims",
              f"    {C} acc = {C}(0);"] + pv("    ", "0u") + [
              f"    coopMatStore(acc, oh, pbase + dc * 64u, {HD}u, {RM});",
              "  }"]
    else:
        L += [f"  for (uint hh = 0u; hh < {CPS}u; ++hh) {{",
              "  uint dc = hh * 2u + sg;  // this round's 64 output dims",
              f"  {C} acc = {C}(0);",
              "  for (uint kp = 0u; 2u * kp < nkb; ++kp) {",
              "    uint kb = kb0 + min(2u * kp + sg, nkb - 1u);",
              "    bool valid = 2u * kp + sg < nkb;"] + qk() + to_p() + ["    barrier();"] + pv("    ", "2u * kp") + [
              "    barrier();",
              "  }"]
        if split:
            L += [f"  coopMatStore(acc, oh, pbase + dc * 64u, {HD}u, {RM});",
                  "  }"]
        else:
            L += [f"  coopMatStore(acc, sh, sb, 17u, {RM});",
                  "  subgroupMemoryBarrierShared(); subgroupBarrier();",
                  "  for (uint j = 0u; j < 8u; ++j) {",
                  "    uint dd = dc * 64u + 8u * j;",
                  "    if (dd < pc.hdv) {",
                  "      uint col = z * pc.hdv + dd;",
                  "      uint oi = (((row / 64u) * (pc.outw / 16u) + col / 16u) * 1024u + l * 16u + col % 16u) / 8u;",
                  "      f16vec4 x = sh[sr + 2u * j], y = sh[sr + 2u * j + 1u];",
                  "      o[oi] = uvec4(packFloat2x16(x.xy), packFloat2x16(x.zw), packFloat2x16(y.xy), packFloat2x16(y.zw));",
                  "    }",
                  "  }",
                  "  barrier();",
                  "  }"]
    L.append("}")
    return "\n".join(L) + "\n"

def main():
    out = HERE / "kernels"
    (out / "fa3.comp").write_text("// generated by gen_kernels.py from ../llama3b/gen_attn.py fa3(): do not edit\n" + fa3())
    fam = []
    for hd in (128, 256):
        for mode in ("", "s", "s1"):
            n = f"famask{hd}{mode}"
            (out / f"{n}.comp").write_text(f"// generated by gen_kernels.py famask({hd}, '{mode}'): do not edit\n" + famask(hd, mode))
            fam.append(n)
    names = ["rowss", "normtiles", "rope_qk", "vtrans", "fa3", "qksplit", "vsplit", "lnstats", "lntiles"] + fam + ["facombine"]
    H = ["// Generated by gen_kernels.py from kernels/*.comp: do not edit.", "#pragma once", "#include <stddef.h>",
         "#include <stdint.h>", ""]
    for n in names:
        spv = out / f"{n}.spv"
        subprocess.run(["glslc", "--target-env=vulkan1.3", "-O", str(out / f"{n}.comp"), "-o", str(spv)], check=True)
        words = [int.from_bytes(spv.read_bytes()[i:i + 4], "little") for i in range(0, spv.stat().st_size, 4)]
        H.append(f"static const uint32_t lt_spv_{n}[] = {{")
        for i in range(0, len(words), 12):
            H.append("  " + ", ".join(f"0x{w:08x}" for w in words[i:i + 12]) + ",")
        H.append("};")
    H.append("enum { " + ", ".join(f"LT_{n.upper()}" for n in names) + ", LT_NKERNELS };")
    H.append("static const struct { const char* name; const uint32_t* spv; size_t words; } lt_kernels[LT_NKERNELS] = {")
    for n in names:
        H.append(f'  {{"{n}", lt_spv_{n}, sizeof(lt_spv_{n}) / 4}},')
    H.append("};")
    (HERE / "ablaslt_kernels.h").write_text("\n".join(H) + "\n")
    print("wrote ablaslt_kernels.h:", ", ".join(names))

main()
