#!/bin/sh
# Builds pi0_lt for Android (Adreno 850): the glue shader into build/glue_spv.h, then the runner with AdrenoBLASLt,
# and the shape_bench / qkv_bench measuring tools.
# Needs glslc and the Android NDK ($NDK_CLANG, default below).
set -e
cd "$(dirname "$0")"
NDK_CLANG=${NDK_CLANG:-/opt/homebrew/share/android-ndk/toolchains/llvm/prebuilt/darwin-x86_64/bin/aarch64-linux-android33-clang}
VK_INC=${VK_INC:-/usr/local/include}
mkdir -p build
(cd ../lt && python3 gen_kernels.py)
glslc --target-env=vulkan1.3 -O glue.comp -o build/glue.spv
python3 - <<'EOF'
b = open("build/glue.spv", "rb").read()
w = [int.from_bytes(b[i:i + 4], "little") for i in range(0, len(b), 4)]
open("build/glue_spv.h", "w").write("// generated by build.sh from glue.comp\nstatic const uint32_t glue_spv[] = {" +
                                    ",".join(f"0x{x:08x}" for x in w) + "};\n")
EOF
for prog in pi0_lt shape_bench qkv_bench; do
  $NDK_CLANG -O2 -Wall -Wno-unused-function -I$VK_INC -o build/$prog $prog.c ../lt/ablasLt.c ../ablas.c -ldl -lm
done
echo "built build/pi0_lt, build/shape_bench, build/qkv_bench"
